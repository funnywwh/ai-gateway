-- M34：曾经用来放"可交互预览的握手凭证"，现在的答案是**不需要凭证**。
--
-- 保留这一列是为了不动已经应用过它的库（迁移是只向前的）。代码完全不读写它，
-- 语义上等价于从来不存在。留给后人的是一句解释，而不是一个谜：
--
-- 这个功能试过两次"秘密"方案，都拆掉了。第一次把凭证放在服务的响应里、让控制台读沙箱
-- 文档取回来——沙箱文档对父窗口是不透明源，contentDocument 恒为 null，于是每份预览都
-- 显示「不可交互」。第二次改成控制台生成、随上传提交、写进页面 URL——但为了让页面里的
-- 嵌套框架读不到它，就得给 script-src 加 nonce，而 nonce 一旦出现，浏览器会**忽略**
-- 'unsafe-inline'，模型页面自己的内联脚本与 onclick 全部被拦（这正是这份文档所描述的
-- 页面赖以工作的东西）。
--
-- 真正需要的事实是结构性的，不是秘密：我们交出的 MessagePort 只能被加载该文档的那个
-- window 收到；注入脚本在自己不是顶层文档时拒绝启动；宿主只接受来自那个 frame 的 hello。
-- 三条合起来与凭证等价，而且不需要任何策略例外。见 internal/httpapi/chat_ui_bridge.go。
